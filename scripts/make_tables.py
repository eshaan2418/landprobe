"""Tables (eval/results/tables.md) and plots (eval/plots/) from raw result JSON."""

from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from landprobe.data import CLASSES, EuroSAT  # noqa: E402

RES = Path("eval/results")
PLOTS = Path("eval/plots")
T95 = {2: 12.706, 3: 4.303, 4: 3.182, 5: 2.776}
LABEL = {"random": "random init (frozen)", "imagenet64": "ImageNet ResNet-18 @64px",
         "imagenet128": "ImageNet ResNet-18 @128px", "simclr": "SimCLR (ours, EuroSAT)",
         "byol": "BYOL (ours, EuroSAT)"}
FT_LABEL = {"random": "supervised from scratch", **{k: v for k, v in LABEL.items()
                                                    if k != "random"}}
COLORS = {"random": "#8C8C8C", "imagenet64": "#DD8452", "imagenet128": "#C44E52",
          "simclr": "#4C72B0", "byol": "#55A868"}


def ci(xs: list[float]) -> tuple[float, float]:
    mu = float(np.mean(xs))
    if len(xs) < 2:
        return mu, float("nan")
    return mu, T95.get(len(xs), 2.0) * float(np.std(xs, ddof=1)) / math.sqrt(len(xs))


def load(kind: str) -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted((RES / kind).glob("*.json"))]


def grid(rows: list[dict], key: str) -> dict[tuple[str, float], dict[int, float]]:
    g: dict[tuple[str, float], dict[int, float]] = defaultdict(dict)
    for r in rows:
        g[(r["backbone"], r["fraction"])][r["seed"]] = r[key]
    return g


def table(g: dict, names: list[str], fracs: list[float], labels: dict, n_labels: dict) -> str:
    head = "| backbone | " + " | ".join(f"{int(f * 100) if f >= 0.01 else f}% ({n_labels[f]})"
                                         for f in fracs) + " |"
    lines = [head, "|---" * (len(fracs) + 1) + "|"]
    for n in names:
        cells = []
        for f in fracs:
            v = list(g.get((n, f), {}).values())
            if not v:
                cells.append("-")
                continue
            mu, h = ci(v)
            cells.append(f"{100 * mu:.1f} ± {100 * h:.1f}")
        lines.append(f"| {labels[n]} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def paired(g: dict, a: str, b: str, f: float) -> tuple[float, float] | None:
    sa, sb = g.get((a, f), {}), g.get((b, f), {})
    seeds = sorted(set(sa) & set(sb))
    if len(seeds) < 2:
        return None
    return ci([sb[s] - sa[s] for s in seeds])


def main() -> None:
    PLOTS.mkdir(parents=True, exist_ok=True)
    out = ["# Results (generated by scripts/make_tables.py)\n"]
    probe = load("probe")
    ft = load("finetune")
    pre = load("pretrain")
    n_labels = {r["fraction"]: r["n_labels"] for r in probe}
    fracs = sorted(n_labels)
    if probe:
        gp = grid(probe, "probe_test")
        gk = grid(probe, "knn_test")
        names = [n for n in ("random", "imagenet64", "imagenet128", "simclr", "byol")
                 if any(k[0] == n for k in gp)]
        out += ["## Linear probe on frozen features, test accuracy % (mean ± 95% t-CI, 3 seeds)\n",
                "Columns: fraction of the 16,200-tile train split that is labelled "
                "(number of labels).\n", table(gp, names, fracs, LABEL, n_labels), "",
                "## Weighted kNN (k=20) on frozen features, test accuracy %\n",
                table(gk, names, fracs, LABEL, n_labels), ""]
        for base in ("imagenet64", "imagenet128", "random"):
            for m in ("simclr", "byol"):
                cells = []
                for f in fracs:
                    d = paired(gp, base, m, f)
                    cells.append("-" if d is None else f"{100 * d[0]:+.1f} ± {100 * d[1]:.1f}")
                out.append(f"- probe Δ {LABEL[m]} − {LABEL[base]}: " + ", ".join(
                    f"{int(f * 100)}%: {c}" for f, c in zip(fracs, cells, strict=True)))
        out.append("")
        fig, ax = plt.subplots(figsize=(5.5, 3.6))
        for n in names:
            xs = [f for f in fracs if (n, f) in gp]
            mus = [100 * ci(list(gp[(n, f)].values()))[0] for f in xs]
            hs = [100 * ci(list(gp[(n, f)].values()))[1] for f in xs]
            ax.errorbar([n_labels[f] for f in xs], mus, yerr=hs, marker="o", capsize=2,
                        label=LABEL[n], color=COLORS[n])
        ax.set_xscale("log")
        ax.set_xlabel("labelled training tiles (log scale)")
        ax.set_ylabel("linear-probe test accuracy %")
        ax.spines[["top", "right"]].set_visible(False)
        ax.legend(frameon=False, fontsize=7)
        fig.tight_layout()
        fig.savefig(PLOTS / "probe_curve.png", dpi=150)
        plt.close(fig)
    if ft:
        gf = grid(ft, "test_acc")
        ffr = sorted({r["fraction"] for r in ft})
        names = [n for n in ("random", "imagenet64", "imagenet128", "simclr", "byol")
                 if any(k[0] == n for k in gf)]
        steps = {r["fraction"]: r["steps"] for r in ft}
        out += ["## Fine-tuning (all layers), test accuracy % (mean ± 95% t-CI, 3 seeds)\n",
                "Fixed recipe for every backbone: AdamW lr 1e-3, wd 0.05, batch 128, cosine; "
                + ", ".join(f"{int(f * 100)}%: {steps[f]} steps" for f in ffr) + ".\n",
                table(gf, names, ffr, FT_LABEL, n_labels), ""]
        im = next((n for n in names if n.startswith("imagenet")), None)
        for m in ("simclr", "byol"):
            for base in [b for b in ("random", im) if b]:
                cells = []
                for f in ffr:
                    d = paired(gf, base, m, f)
                    cells.append("-" if d is None else f"{100 * d[0]:+.1f} ± {100 * d[1]:.1f}")
                out.append(f"- fine-tune Δ {FT_LABEL[m]} − {FT_LABEL[base]}: " + ", ".join(
                    f"{int(f * 100)}%: {c}" for f, c in zip(ffr, cells, strict=True)))
        tsec = defaultdict(list)
        for r in ft:
            tsec[(r["backbone"], r["fraction"])].append(r["train_s"])
        out.append("\nFine-tune wall-clock per run (s): " + "; ".join(
            f"{k[0]}@{int(k[1] * 100)}% {np.mean(v):.0f}" for k, v in sorted(tsec.items())))
        out.append("")
        _confusion(ft, out)
    if pre:
        out += ["## Pretraining runs\n",
                "| run | epochs | wall min | peak MPS GB | final loss | kNN val % (100% labels) |",
                "|---|---|---|---|---|---|"]
        for p in pre:
            last = p["log"][-1]
            out.append(f"| {p['config']['name']} | {p['config']['epochs']} | "
                       f"{p['wall_s'] / 60:.1f} | {p['peak_memory_gb']:.1f} | "
                       f"{last['loss']:.3f} | {100 * last.get('knn_val_acc', float('nan')):.1f} |")
        out.append(f"\nTotal pretraining: {sum(p['wall_s'] for p in pre) / 3600:.2f} h.\n")
        fig, ax = plt.subplots(figsize=(5, 3.2))
        for p in pre:
            m = p["config"]["method"]
            pts = [(r["epoch"], 100 * r["knn_val_acc"]) for r in p["log"] if "knn_val_acc" in r]
            ax.plot(*zip(*pts, strict=True), marker=".", color=COLORS[m], alpha=0.8,
                    label=m if p["config"]["seed"] == 0 else None)
        ax.set_xlabel("pretraining epoch")
        ax.set_ylabel("kNN val accuracy %")
        ax.spines[["top", "right"]].set_visible(False)
        ax.legend(frameon=False)
        fig.tight_layout()
        fig.savefig(PLOTS / "pretrain_knn.png", dpi=150)
        plt.close(fig)
    tp = RES / "bench" / "throughput.json"
    if tp.exists():
        t = json.loads(tp.read_text())
        out += ["## Training throughput, ResNet-18, batch 256, 64x64 input\n",
                "| stem | channels_last | img/s |", "|---|---|---|"]
        out += [f"| {r['stem']} | {r['channels_last']} | {r['train_img_per_s']:.0f} |"
                for r in t["rows"]]
        out.append("")
    (RES / "tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


def _confusion(ft: list[dict], out: list[str]) -> None:
    """Confusion matrix of the best 1%-label fine-tuned model family (summed over seeds)."""
    data = EuroSAT.load()
    te = data.splits["test"]
    y = data.labels[te]
    one = [r for r in ft if r["fraction"] == 0.01 and r.get("test_pred")]
    if not one:
        return
    by = defaultdict(list)
    for r in one:
        by[r["backbone"]].append(r)
    best = max(by, key=lambda k: np.mean([r["test_acc"] for r in by[k]]))
    cm = np.zeros((10, 10), dtype=int)
    for r in by[best]:
        for t, p in zip(y, r["test_pred"], strict=True):
            cm[t, p] += 1
    recall = cm.diagonal() / cm.sum(1)
    off = [(cm[i, j], CLASSES[i], CLASSES[j]) for i in range(10) for j in range(10) if i != j]
    off.sort(reverse=True)
    out.append(f"### Error analysis: {FT_LABEL[best]} fine-tuned on 1% labels "
               f"(test predictions summed over {len(by[best])} seeds)\n")
    out.append("Per-class recall: " + ", ".join(
        f"{c} {100 * r:.0f}%" for c, r in sorted(zip(CLASSES, recall, strict=True),
                                                 key=lambda x: x[1])))
    out.append("\nMost frequent confusions (true -> predicted, count): " + "; ".join(
        f"{a} -> {b} {n}" for n, a, b in off[:6]) + "\n")
    fig, ax = plt.subplots(figsize=(5.5, 5))
    ax.imshow(cm / cm.sum(1, keepdims=True), cmap="Blues", vmin=0, vmax=1)
    ax.set_xticks(range(10), CLASSES, rotation=60, ha="right", fontsize=7)
    ax.set_yticks(range(10), CLASSES, fontsize=7)
    ax.set_xlabel("predicted")
    ax.set_ylabel("true")
    for i in range(10):
        for j in range(10):
            v = cm[i, j] / cm[i].sum()
            if v >= 0.05:
                ax.text(j, i, f"{100 * v:.0f}", ha="center", va="center", fontsize=6,
                        color="white" if v > 0.5 else "black")
    fig.tight_layout()
    fig.savefig(PLOTS / "confusion_1pct.png", dpi=150)
    plt.close(fig)


if __name__ == "__main__":
    main()
